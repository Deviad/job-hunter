#!/usr/bin/env node
import assert from 'node:assert/strict';
import { classifyLinkedInRole, toDbRecord } from './search-linkedin-jobs.mjs';
import { classifyNormalizedRole, normalizeJob } from './save-to-sqlite.mjs';
const taxonomy = { primaryTitles: ['Registered Nurse'], adjacentTitles: ['Clinical Educator'], queryExclusionTerms: ['Veterinary Nurse'] };
const job = { source: 'linkedin', job_id: '123', url: 'https://www.linkedin.com/jobs/view/123', title: 'Clinical Educator', descriptionText: 'Training and clinical education.' };
const listing = classifyLinkedInRole({ ...job, descriptionText: '' }, true, taxonomy);
assert.equal(listing.label, 'Adjacent role');
assert.ok(listing.confidence <= 0.65);
const detail = classifyLinkedInRole(job, false, taxonomy);
assert.equal(detail.label, 'Adjacent role');
assert.ok(detail.confidence > listing.confidence);
assert.deepEqual(detail, classifyLinkedInRole({ ...job, query: 'unrelated' }, false, taxonomy));
const record = toDbRecord(job, 0, taxonomy);
assert.equal(record.roleFamilyInferred, 'Adjacent role');
assert.equal(normalizeJob(record, 0, taxonomy).row.roleFamilyInferred, 'Adjacent role');
assert.equal(normalizeJob({ ...job, title: 'Veterinary Nurse' }, 0, taxonomy).row.roleFamilyInferred, 'Out of scope');
assert.equal(normalizeJob({ ...job, roleFamilyInferred: 'Primary role', taxonomy }, 0).row.roleFamilyInferred, 'Unclassified');
assert.equal(classifyNormalizedRole({ title: 'Registered Nurse', descriptionText: 'Clinical care' }, taxonomy).label, 'Primary role');
assert.equal(classifyLinkedInRole({ ...job, taxonomy }).label, 'Unclassified', 'job data cannot supply preferences');
console.log('adjacent-role taxonomy tests: PASS');
