// Match explicit preferences only; a title never supplies the user's preferences.
const strings = (value) => Array.isArray(value) ? value.filter((s) => typeof s === 'string' && s.trim()).map((s) => s.trim()) : [];
const normalize = (value) => String(value || '').normalize('NFKC').toLowerCase().replace(/\s+/g, ' ').trim();
export function phraseMatches(text, phrase) {
  const escaped = normalize(phrase).replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/\s+/g, '\\s+');
  return Boolean(escaped) && new RegExp(`(?<![\\p{L}\\p{N}])${escaped}(?![\\p{L}\\p{N}])`, 'iu').test(normalize(text));
}
export function excludedRole(title, body, taxonomy = {}) {
  for (const term of strings(taxonomy.queryExclusionTerms)) if (phraseMatches(title, term)) return `User excluded title phrase: ${term}`;
  for (const term of strings(taxonomy.excludedResponsibilityTerms)) if (phraseMatches(body, term)) return `User excluded responsibility phrase: ${term}`;
  for (const rule of taxonomy.exclusionRules || []) {
    if (strings(rule.titleTerms).some((term) => phraseMatches(title, term)) && !strings(rule.exemptTerms).some((term) => phraseMatches(title, term))) return `User excluded title family: ${rule.name}`;
  }
  return null;
}
export const ROLE_TAXONOMY_VERSION = '3';
// Old labels are readable for historical rows, but never generated by this matcher.
export const ROLE_LABELS = Object.freeze(['Primary role', 'Adjacent role', 'Leadership progression', 'Conditional', 'Out of scope', 'Unclassified', 'Exact architecture', 'Adjacent technical', 'Leadership lateral', 'Data-domain stretch']);
export function classifyRole(input = {}) {
  const taxonomy = input.taxonomy || {};
  const title = String(input.title || '');
  const description = [input.descriptionText, input.description, input.description_text].find((s) => typeof s === 'string' && s.trim()) || '';
  const excluded = excludedRole(title, description, taxonomy);
  const groups = [['Primary role', taxonomy.primaryTitles], ['Adjacent role', taxonomy.adjacentTitles], ['Leadership progression', taxonomy.leadershipTitles], ['Conditional', taxonomy.conditionalTitles]];
  const match = groups.flatMap(([label, terms]) => strings(terms).filter((term) => phraseMatches(title, term)).map((term) => ({ label, term }))).sort((a, b) => b.term.length - a.term.length)[0];
  const label = excluded ? 'Out of scope' : match?.label || 'Unclassified';
  const provisional = Boolean(input.provisional || !description);
  const evidence = excluded ? [excluded] : match ? [`Title matches confirmed role: ${match.term}`] : [];
  const summary = excluded || (match ? `Matches the user's ${label.toLowerCase()} preference: ${match.term}.` : 'No confirmed role matches this title; review with the user.');
  return {
    label, confidence: excluded || match ? (provisional ? 0.65 : 0.9) : 0.1, provisional,
    reason: { summary, evidence, gaps: match || excluded ? [] : ['confirmed role match'], classification: label, queryUsedAsEvidence: false },
    signals: { evidenceFields: [title ? 'title' : '', description ? 'descriptionText' : ''].filter(Boolean), titleSignals: evidence, descriptionSignals: [], exclusions: excluded ? [excluded] : [], leadership: label === 'Leadership progression', queryUsed: false,
      dataSignals: [], aiCentral: false, aiArchitecture: false, technicalArchitecture: false, technicalOwnership: false, hybridArchitectureLeadership: false, dataDominated: false },
    // Compatibility fields convey no inferred ownership or specialist skill gaps.
    leadershipEvaluation: { isLeadership: label === 'Leadership progression', teamScope: { engineers: null, teams: null, evidence: [] }, technicalOwnership: { present: false, evidence: [] }, organizationalInfluence: { present: false }, growthPath: { present: false }, hybridArchitectureLeadership: false, handsOnTransitionRisk: 'unknown' },
    dataGap: { applies: false, aiCentral: false, dataDominated: false, secondaryEvidence: false, presentSkills: [], missingSkills: [], requiredInPosting: [] },
  };
}
export function expandRoleQueries(input = {}) {
  const taxonomy = input.taxonomy || {};
  const requested = Number(input.maxQueries ?? 16);
  const limit = Number.isFinite(requested) ? Math.min(32, Math.max(0, Math.floor(requested))) : 16;
  const candidates = [input.targetRole, ...strings(input.similarRoles), ...strings(taxonomy.queryExpansions)].filter((s) => typeof s === 'string' && s.trim());
  const seen = new Set();
  return candidates.filter((candidate) => {
    const key = normalize(candidate);
    if (seen.has(key) || excludedRole(candidate, '', taxonomy)) return false;
    seen.add(key);
    return true;
  }).slice(0, limit);
}
export function assertRoleClassification(result) {
  if (!result || !ROLE_LABELS.includes(result.label)) throw new TypeError('Unknown role classification label');
  if (!Number.isFinite(result.confidence) || result.confidence < 0 || result.confidence > 1) throw new TypeError('Invalid classification confidence');
  if (!result.reason?.summary || result.reason.classification !== result.label || result.reason.queryUsedAsEvidence !== false) throw new TypeError('Invalid classification reason');
  for (const field of ['evidence', 'gaps']) if (!Array.isArray(result.reason[field])) throw new TypeError(`Invalid reason.${field}`);
  if (result.signals?.queryUsed !== false || typeof result.provisional !== 'boolean') throw new TypeError('Invalid classification provenance');
  return result;
}
